"""Splits the animated Goodtime State stickers (site/img/sticker-<name>.webp) into sprite sheets for the
animated Story export, plus the frame table site/js/sticker-frames.js.

A sheet decodes the same in every browser that can encode the video; ImageDecoder, which could read the
WebP directly, is missing in Safari. Pillow composites the frames through libwebp's own animation decoder
(ImageMagick 6 mis-blends them: doubled glasses, grey boxes). Outputs are committed.

  /tmp/bp-fonts/venv/bin/python -I scripts/stickers.py      # fonts.sh creates that venv with Pillow
"""
import json
import pathlib

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
IMG = ROOT / 'site' / 'img'
COLS = 8
table = {}
for name in ('gator', 'sun', 'flamingo', 'manatee'):
    with Image.open(IMG / f'sticker-{name}.webp') as im:
        w, h, count = im.width, im.height, im.n_frames
        sheet = Image.new('RGBA', (COLS * w, -(-count // COLS) * h), (0, 0, 0, 0))
        delays = []
        for i in range(count):
            im.seek(i)
            sheet.paste(im.convert('RGBA'), ((i % COLS) * w, (i // COLS) * h))
            delays.append(im.info['duration'])
    sheet.save(IMG / f'sticker-{name}-sheet.webp', quality=86, alpha_quality=100, method=6)
    table[name] = {'w': w, 'h': h, 'cols': COLS, 'count': count, 'delays': delays}
    print(f'{name}: {count} frames, {sum(delays)} ms loop')

(ROOT / 'site' / 'js' / 'sticker-frames.js').write_text(
    '// Generated by scripts/stickers.py: sprite sheet layout and per-frame delays (ms) of each animated sticker.\n'
    'export const FRAMES = {\n' + ''.join(f'  {k}: {json.dumps(v, separators=(", ", ": "))},\n' for k, v in table.items()) + '};\n')
