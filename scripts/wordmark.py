#!/usr/bin/env python3
"""Outlines the FlyUS wordmark into site/js/wordmark.js.

"fly" is semi-condensed bold Archivo; "US" is black italic Archivo with extra shear, U and S overlapped so they
fuse into one shape, the S's lower-left aperture filled in, and a 5-point star knocked out of that solid
area (the background shows through it, as on the template ticket). Union and cut-out are real boolean
ops (skia-pathops), so `d` is one plain path that renders right under any fill rule and `star` is empty.
Positions follow the measured ink of the template logo (ticket-spec section 4.1); the letters are Archivo
(OFL), nothing is traced.

Run after scripts/fonts.sh has downloaded the sources (needs `pip install skia-pathops` in its venv):
  /tmp/bp-fonts/venv/bin/python -I scripts/wordmark.py
"""
import math
import pathlib
import sys

import pathops
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '/tmp/bp-fonts')
OUT = pathlib.Path(__file__).resolve().parent.parent / 'site' / 'js' / 'wordmark.js'


def num(v):
    s = f'{round(v, 1):.1f}'.rstrip('0').rstrip('.')
    return '0' if s == '-0' else s


def glyph(font, ch, size, origin, scale_x=1.0, shear=0.0):
    """One glyph as a pathops.Path: `size` px, baseline-left at `origin`, squeezed by `scale_x`,
    slanted right by `shear` (dx per px of height)."""
    glyphs = font.getGlyphSet()
    k = size / font['head'].unitsPerEm
    p = pathops.Path()
    # font units (y up) -> ticket px (y down): x' = ox + sx*k*gx + shear*k*gy, y' = oy - k*gy
    glyphs[font.getBestCmap()[ord(ch)]].draw(TransformPen(p.getPen(), (scale_x * k, 0, shear * k, -k, *origin)))
    return p


def poly(pts):
    p = pathops.Path()
    pen = p.getPen()
    pen.moveTo(pts[0])
    for q in pts[1:]:
        pen.lineTo(q)
    pen.closePath()
    return p


def star(cx, cy, r, inner, shear):
    """5-point star, point up, slanted like the italics (dx = -shear * dy)."""
    pts = []
    for i in range(10):
        a, rr = math.radians(-90 + i * 36), (r if i % 2 == 0 else r * inner)
        dy = rr * math.sin(a)
        pts.append((cx + rr * math.cos(a) - shear * dy, cy + dy))
    return poly(pts)


def union(*paths):
    out = paths[0]
    for p in paths[1:]:
        out = pathops.op(out, p, pathops.PathOp.UNION)
    return out


def main():
    upright = instantiateVariableFont(TTFont(SRC / 'Archivo.ttf'), {'wdth': 85, 'wght': 700})
    italic = instantiateVariableFont(TTFont(SRC / 'Archivo-Italic.ttf'), {'wdth': 100, 'wght': 900})
    fly = union(glyph(upright, 'f', 104, (130.5, 96), 1.1), glyph(upright, 'l', 104, (163, 96)),
                glyph(upright, 'y', 104, (189.5, 96), 0.95))
    sh = 0.13  # on top of Archivo Italic's own 10 deg -> ~17 deg, the template's slant
    u = glyph(italic, 'U', 107, (224, 95.5), 0.95, sh)
    s = glyph(italic, 'S', 107, (283.5, 95.5), 1.05, sh)
    fill = poly([(293, 60), (342, 60), (342, 82), (290, 82)])  # closes the S's lower-left aperture
    us = pathops.op(union(u, s, fill), star(326.5, 71.7, 17.8, 0.42, 0.2), pathops.PathOp.DIFFERENCE)
    mark = union(fly, us)
    pen = SVGPathPen(None, num)
    mark.draw(pen)
    box = mark.bounds
    OUT.write_text(
        '// Generated by scripts/wordmark.py from Archivo (OFL): "fly" wdth 85 wght 700; "US" italic wdth 100 wght 900\n'
        '// sheared to ~17 deg, U and S fused, the S\'s lower aperture filled and a star knocked out of it (boolean ops,\n'
        '// so `d` is one plain path and `star` is empty). Ticket coordinates (main logo). Do not edit by hand.\n'
        f"export const WORDMARK = {{ d: '{pen.getCommands()}', star: '', bbox: [{', '.join(num(v) for v in box)}] }};\n")
    print(f'{OUT}: fly {[num(v) for v in fly.bounds]} US {[num(v) for v in us.bounds]}')


if __name__ == '__main__':
    main()
